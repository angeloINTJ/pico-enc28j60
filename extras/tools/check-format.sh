# The formatting check of the CI, in one place: the job "clang-format" runs this script, and so does
# check-commits.sh on the tree of each commit, so the list of files and the options cannot differ
# between them. See --help.
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: check-format.sh [DIR]

Check that clang-format 18 has nothing to change in the C and C++ sources of the tree in DIR
(default: the repository this script is in). It is the check of the job "clang-format" of the CI.
enc28j60-spi.pio.h is generated by pioasm and left as it is.

Environment:
  CLANG_FORMAT   the clang-format to run (default: clang-format-18; other versions format differently)

Exit status: 0 if nothing would change, 1 if something would (clang-format says what and where),
2 if the check could not be made. clang-format -i on the files it names fixes them.
EOF
}

case ${1:-} in
    -h | --help)
        usage
        exit 0
        ;;
    -?*)
        echo "check-format: unknown option: $1" >&2
        usage >&2
        exit 2
        ;;
esac
if [[ $# -gt 1 ]]; then
    usage >&2
    exit 2
fi

tree=${1:-$(dirname "$0")/../..}
clang_format=${CLANG_FORMAT:-clang-format-18}
if ! command -v "$clang_format" > /dev/null 2>&1; then
    echo "check-format: $clang_format not found: install clang-format 18, or set CLANG_FORMAT" >&2
    exit 2
fi
if [[ ! -d $tree ]]; then
    echo "check-format: $tree is not a directory" >&2
    exit 2
fi
cd "$tree"

exec "$clang_format" --dry-run --Werror \
    src/*.c src/*.cpp src/PicoENC28J60.h src/PicoENC28J60lwIP.h \
    src/enc28j60-cmd.h src/pico/*.h freertos/*.c freertos/pico/*.h
